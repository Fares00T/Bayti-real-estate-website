// French plural: 0 and 1 are singular
const many = (n) => Number(n) > 1;
// "18 500 000" keeps its narrow non-breaking spaces
const nb = (s) => s.replace(/ /g, "\u202f");
// "2026-11-14" -> "14/11/2026"
const frDate = (s) => s.replace(/^(\d{4})-(\d{2})-(\d{2})$/, "$3/$2/$1");
// "12 nov. 2026" -> "le 12 nov. 2026"; "il y a 2 h" stays
const when = (s, t) => {
  const fr = t(s);
  return /^\d/.test(fr) ? `le ${fr}` : fr;
};
const ROLE_LOWER = { owner: "propriétaire", manager: "responsable", agent: "agent" };
// Inquiry states as counted on a listing page: [singular, plural]
const INQUIRY_COUNT = {
  open: ["à traiter", "à traiter"],
  "visit confirmed": ["visite confirmée", "visites confirmées"],
  declined: ["refusée", "refusées"],
  closed: ["clôturée", "clôturées"],
  "cancelled by client": ["annulée par le client", "annulées par le client"],
};
// "2 open · 1 visit confirmed" -> "2 à traiter · 1 visite confirmée"
const inquiryCounts = (m) =>
  m[0]
    .split(" · ")
    .map((part) => {
      const [, n, state] = /^(\d+) (.+)$/.exec(part);
      return `${n} ${INQUIRY_COUNT[state][many(n) ? 1 : 0]}`;
    })
    .join(" · ");
// components/Feed.jsx lowercases the first letter of an activity summary so that it reads on after
// the member's name ("Sara created…"): look the sentence up with its capital and lowercase the
// French the same way. Returns nothing when the sentence is unknown, which counts as no match.
const afterName = (m, t) => {
  const en = m[0].charAt(0).toUpperCase() + m[0].slice(1);
  const fr = t(en);
  return fr === en ? null : fr.charAt(0).toLowerCase() + fr.slice(1);
};

