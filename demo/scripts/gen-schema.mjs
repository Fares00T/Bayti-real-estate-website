// Embeds server/schema.prisma as a JS module so the in-browser database (and
// Node smoke tests) can read it without a bundler plugin.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../server/", import.meta.url));
const schema = readFileSync(root + "schema.prisma", "utf8");
writeFileSync(root + "runtime/schema.js", `// Generated by scripts/gen-schema.mjs from server/schema.prisma\nexport default ${JSON.stringify(schema)};\n`);
console.log("server/runtime/schema.js written");
