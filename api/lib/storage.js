import crypto from "crypto";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import multer from "multer";
import prisma from "./prisma.js";

// Private files (legal documents, report screenshots) are written to a folder
// outside every static path, under random names. They're only ever streamed by
// endpoints that have checked who is asking. Set STORAGE_DIR to a persistent
// volume in production.
const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(process.env.STORAGE_DIR || path.join(here, "..", "storage", "private"));

export const MAX_FILE_BYTES = 10 * 1024 * 1024;
export const MAX_FILES = 10;

// Detect the real type from the file's first bytes; the browser's claimed
// MIME type and the extension are never trusted.
const SIGNATURES = [
  { mime: "application/pdf", ext: "pdf", test: (b) => b.subarray(0, 5).toString("latin1") === "%PDF-" },
  { mime: "image/png", ext: "png", test: (b) => b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) },
  { mime: "image/jpeg", ext: "jpg", test: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
];
const ALLOWED_EXT = /\.(pdf|jpe?g|png)$/i;

export const sniff = (buffer) =>
  buffer && buffer.length > 8 ? SIGNATURES.find((s) => s.test(buffer)) || null : null;

// Multer keeps files in memory so nothing touches the disk before validation
export const uploadMiddleware = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: MAX_FILE_BYTES, files: MAX_FILES },
});

// Wraps a multer handler so its errors come back as clean 400s
export const acceptFiles = (handler) => (req, res, next) =>
  handler(req, res, (err) => {
    if (!err) return next();
    const message =
      err.code === "LIMIT_FILE_SIZE"
        ? `Each file must be ${MAX_FILE_BYTES / 1024 / 1024} MB or smaller.`
        : err.code === "LIMIT_FILE_COUNT" || err.code === "LIMIT_UNEXPECTED_FILE"
        ? `You can upload up to ${MAX_FILES} files at once.`
        : "The upload failed.";
    res.status(400).json({ message });
  });

// Returns an error message, or null if the file is acceptable
export const validateFile = (file) => {
  if (!file?.buffer?.length) return "The file is empty.";
  if (!ALLOWED_EXT.test(file.originalname || "")) return `${file.originalname}: only PDF, JPG and PNG files are accepted.`;
  if (!sniff(file.buffer)) return `${file.originalname} isn't a valid PDF, JPG or PNG file.`;
  return null;
};

const safeName = (name = "file") =>
  path.basename(name).replace(/[^\w.\- ()]/g, "_").slice(0, 150) || "file";

// Saves a validated file and creates its Document row. `links` sets the owner
// (applicationId, agencyId, reportId or userId).
export const storeDocument = async (file, { kind, uploadedById, ...links }) => {
  const type = sniff(file.buffer);
  const storageKey = `${crypto.randomBytes(24).toString("hex")}.${type.ext}`;
  await fs.promises.mkdir(ROOT, { recursive: true });
  await fs.promises.writeFile(path.join(ROOT, storageKey), file.buffer, { mode: 0o600 });
  try {
    return await prisma.document.create({
      data: {
        kind,
        originalName: safeName(file.originalname),
        mimeType: type.mime,
        size: file.size,
        storageKey,
        sha256: crypto.createHash("sha256").update(file.buffer).digest("hex"),
        uploadedById: uploadedById ?? null,
        ...links,
      },
    });
  } catch (err) {
    await removeFile(storageKey);
    throw err;
  }
};

const resolveKey = (storageKey) => {
  // storage keys are generated by us, but never let one escape the folder
  if (!/^[a-f0-9]{48}\.(pdf|png|jpg)$/.test(storageKey)) throw new Error("Bad storage key");
  return path.join(ROOT, storageKey);
};

export const removeFile = async (storageKey) => {
  try {
    await fs.promises.unlink(resolveKey(storageKey));
  } catch {
    // already gone
  }
};

// Deletes Document rows and their files
export const deleteDocuments = async (where) => {
  const docs = await prisma.document.findMany({ where, select: { id: true, storageKey: true } });
  if (!docs.length) return 0;
  await prisma.document.deleteMany({ where: { id: { in: docs.map((d) => d.id) } } });
  await Promise.all(docs.map((d) => removeFile(d.storageKey)));
  return docs.length;
};

// Streams a document. Callers must have authorized the request already.
export const sendDocument = (res, doc, { download = false } = {}) => {
  let filePath;
  try {
    filePath = resolveKey(doc.storageKey);
  } catch {
    return res.status(404).json({ message: "File not found." });
  }
  if (!fs.existsSync(filePath)) return res.status(404).json({ message: "File not found." });

  const disposition = download ? "attachment" : "inline";
  res.setHeader("Content-Type", doc.mimeType);
  res.setHeader("Content-Length", doc.size);
  res.setHeader(
    "Content-Disposition",
    `${disposition}; filename="${doc.originalName.replace(/"/g, "")}"; filename*=UTF-8''${encodeURIComponent(doc.originalName)}`
  );
  res.setHeader("X-Content-Type-Options", "nosniff");
  res.setHeader("Cache-Control", "private, no-store");
  fs.createReadStream(filePath).pipe(res);
};

// Fields of a Document that are safe to send to a browser
export const publicDocument = ({ storageKey, sha256, ...doc }) => doc;
